import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import path from 'node:path';
import os from 'node:os';
const { canCheckPermission } = createRequire(import.meta.url)('../desktop/permissions.cjs');
const main = { getURL: () => 'tagmaestro://app/' };
const origin = 'tagmaestro://app';
const details = { filePath: path.join(os.tmpdir(), 'synthetic.wav'), fileAccessType: 'readable' };
assert.equal(canCheckPermission(main, 'fileSystem', origin, details, main), true);
assert.equal(canCheckPermission(null, 'fileSystem', origin, details, main), true);
assert.equal(canCheckPermission(null, 'fileSystem', origin, { ...details, isDirectory: true, fileAccessType: 'writable' }, main), true);
for (const otherOrigin of ['https://example.com', 'file:///tmp/test', 'tagmaestro://other', 'null']) assert.equal(canCheckPermission(null, 'fileSystem', otherOrigin, details, main), false);
assert.equal(canCheckPermission(null, 'fileSystem', origin, {}, main), false);
assert.equal(canCheckPermission(null, 'fileSystem', origin, {filePath:'relative.wav'}, main), false);
assert.equal(canCheckPermission({ getURL: () => origin }, 'fileSystem', origin, details, main), false);
assert.equal(canCheckPermission(null, 'clipboard-sanitized-write', origin, details, main), false);
assert.equal(canCheckPermission(main, 'camera', origin, details, main), false);
assert.equal(canCheckPermission(null, 'fileSystem', origin, details, {getURL: () => 'https://example.com'}), false);
assert.equal(canCheckPermission(null, 'fileSystem', origin, details, undefined), false);
console.log('PASS: Electron null-WebContents external file/directory checks; foreign origins, other windows, missing paths and unrelated permissions denied.');
